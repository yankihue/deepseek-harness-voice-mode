    // fold a SessionLogSnapshot into plain spoken text (scalars only)
    // // VERIFY(SessionEvent user/message + assistant/message text blocks) —
    // //   defensive leaf reads of the cloned log; dsh-session types: 'user/message'
    // //   and 'assistant/message' events carry {message:{content:[{type,text}]}}
    function foldSessionText(snap) {
      var events = (snap && snap.events) || [];
      var out = [];
      var start = Math.max(0, events.length - 40);
      for (var i = start; i < events.length; i++) {
        var ev = events[i];
        if (!ev || typeof ev.type !== 'string') continue;
        if (ev.type !== 'user/message' && ev.type !== 'assistant/message') continue;
        var msg = ev.message;
        if (!msg || !Array.isArray(msg.content)) continue;
        for (var j = 0; j < msg.content.length; j++) {
          var block = msg.content[j];
          if (block && block.type === 'text' && typeof block.text === 'string' && block.text.length) {
            out.push(block.text);
          }
        }
      }
      return out.join('\n');
    }
    // leaf extraction for reply watches: the assembled assistant message of an
    // 'assistant/message' session event (data.message.content text blocks) —
    // // VERIFY(dsh-session types SessionEventMap 'assistant/message' shape:
    // //   {turn, step, message:{id,role,content:[{type:'text',text}]}}) — verified
    function assistantTextOf(ev) {
      var data = ev && ev.data;
      var msg = data && data.message;
      if (!msg || !Array.isArray(msg.content)) return null;
      var out = '';
      for (var i = 0; i < msg.content.length; i++) {
        var b = msg.content[i];
        if (b && b.type === 'text' && typeof b.text === 'string') out += b.text;
      }
      return out.length ? out : null;
    }
    // Markdown -> speech: drop code fences (read aloud they are garbage), unwrap
    // inline code/links, strip emphasis/bullet decoration, collapse whitespace.
    function sanitizeSpeech(text) {
      if (!isNonEmptyString(text)) return '';
      var t = text
        .replace(/```[\s\S]*?```/g, ' ')
        .replace(/`([^`]*)`/g, '$1')
        .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
        .replace(/[*_~>|#]/g, ' ')
        .replace(/^\s*[-+]\s+/gm, ' ')
        .replace(/\s+/g, ' ')
        .trim();
      if (t.length > REPLY_MAX_CHARS) t = t.slice(0, REPLY_MAX_CHARS) + ' …';
      return t;
    }

