    IntentRouter.prototype.route = function (transcript) {
      var st = this.state;
      var startedAt = Date.now();
      var local = deterministicRoute(transcript);
      if (local) {
        recordRoute(st, 'deterministic', local.verb, null, startedAt, null);
        return this.execute(transcript, local);
      }
      var llm = st.svc.llm;
      var model = currentModel(st.svc);
      if (!llm || !model.provider) {
        recordRoute(st, 'fallback', 'route_current', 'model_unavailable', startedAt, model);
        return this.execute(transcript, { verb: 'route_current', text: transcript });
      }
      var options = {
        provider: model.provider,
        model: model.model,
        purpose: 'voice-intent-router',
        reasoningEffort: ROUTER_REASONING_EFFORT,
        messages: [{ role: 'user', content: [{ type: 'text', text: transcript }] }],
        system: ROUTER_SYSTEM,
        temperature: 0,
        maxTokens: 160,
      };
      var modelResult = Promise.resolve().then(function () { return collectStream(llm.stream(options)); })
        .then(function (raw) { return { kind: 'model', raw: raw }; }, function () { return { kind: 'error' }; });
      var deadline = ctx.timeout(ROUTER_TIMEOUT_MS).then(function () { return { kind: 'timeout' }; });
      return Promise.race([modelResult, deadline]).then(function (result) {
        if (result.kind === 'error') {
          recordRoute(st, 'fallback', 'route_current', 'model_error', startedAt, model);
          return this.execute(transcript, { verb: 'route_current', text: transcript });
        }
        var parsed = result.kind === 'model' ? parseRouterJson(result.raw) : null;
        if (!parsed) {
          var reason = result.kind === 'timeout' ? 'timeout' : 'invalid_json';
          recordRoute(st, 'fallback', 'route_current', reason, startedAt, model);
          return this.execute(transcript, { verb: 'route_current', text: transcript });
        }
        recordRoute(st, 'llm', parsed.verb, null, startedAt, model);
        return this.execute(transcript, parsed);
      }.bind(this));
    };
    // verb -> service mapping (PROTOCOL §4); every service via ctx.get with
    // absence checks; nothing here may throw out of the async chain
    IntentRouter.prototype.execute = function (rawTranscript, parsed) {
      var st = this.state;
      var tm = st.threads;
      var verb = parsed.verb;
      var text = parsed.text || rawTranscript;
      if (verb === 'create_thread') {
        return tm.create(parsed.threadTitle, text).then(function (r) {
          return { verb: verb, ok: r.ok, id: r.id, title: r.title };
        });
      }
      if (verb === 'message_thread') {
        var target = resolveTarget(tm, parsed.threadTitle);
        if (!target) {
          return tm.create(null, text).then(function (r) {
            return { verb: 'create_thread', ok: r.ok, id: r.id, title: r.title };
          });
        }
        return tm.message(target.id, text).then(function (r) { return { verb: verb, ok: r.ok, id: target.id }; });
      }
      if (verb === 'status') {
        return tm.refresh().then(function () {
          var summary = tm.statusSummary();
          st.queue.push(summary, 2);
          return { verb: verb, ok: true, summary: summary };
        });
      }
      if (verb === 'interrupt') {
        var t2 = resolveTarget(tm, parsed.threadTitle);
        if (!t2) return Promise.resolve({ verb: verb, ok: false, code: 'no_such_thread' });
        return tm.interrupt(t2.id).then(function (r) { return { verb: verb, ok: r.ok, id: t2.id }; });
      }
      if (verb === 'summarize') {
        var t3 = resolveTarget(tm, parsed.threadTitle);
        if (!t3) return Promise.resolve({ verb: verb, ok: false, code: 'no_such_thread' });
        return tm.summarize(t3.id).then(function (r) { return { verb: verb, ok: r.ok, id: t3.id }; });
      }
      if (verb === 'speak_only') {
        if (isNonEmptyString(parsed.text)) st.queue.push(parsed.text, 1);
        return Promise.resolve({ verb: verb, ok: true, spoken: isNonEmptyString(parsed.text) });
      }
      // route_current: insert into the bound current thread (default: most recent
      // active thread; fallback creates one). The target becomes the voice
      // "conversation channel" so follow-up chatter stays in the same chat.
      var now = tm.current();
      if (now) {
        st.conversationId = now.id;
        return tm.message(now.id, text).then(function (r) { return { verb: verb, ok: r.ok, id: now.id, fallback: false }; });
      }
      return tm.create(null, text).then(function (r) {
        if (r.ok) st.conversationId = r.id;
        return { verb: verb, ok: r.ok, id: r.id, fallback: true };
      });
    };
    function resolveTarget(tm, hint) {
      if (isNonEmptyString(hint)) {
        if (tm.isLive(hint)) return { id: hint };
        var rows = tm.rows();
        for (var i = 0; i < rows.length; i++) {
          if (rows[i].title === hint) return { id: rows[i].id };
          if (rows[i].title && rows[i].title.indexOf(hint) >= 0) return { id: rows[i].id };
        }
      }
      return tm.current();
    }
