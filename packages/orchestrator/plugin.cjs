    function collectStream(stream) {
      var text = '';
      var done = false;
      return Promise.resolve().then(function () {
        var iter = stream[Symbol.asyncIterator] ? stream[Symbol.asyncIterator]() : stream;
        function step() {
          return iter.next().then(function (r) {
            if (r.done) return;
            var chunk = r.value;
            if (chunk && chunk.type === 'text-delta' && typeof chunk.text === 'string') text += chunk.text;
            if (chunk && chunk.type === 'finish') { done = true; return; }
            return step();
          });
        }
        return step();
      }).then(function () { return text; });
    }
    function parseRouterJson(raw) {
      if (!isNonEmptyString(raw)) return null;
      var cleaned = raw.trim();
      // strip markdown fences if the model wrapped the object
      var m = cleaned.match(/```(?:json)?\s*([\s\S]*?)```/);
      if (m) cleaned = m[1].trim();
      var start = cleaned.indexOf('{');
      var end = cleaned.lastIndexOf('}');
      if (start < 0 || end < start) return null;
      var obj = null;
      try { obj = JSON.parse(cleaned.slice(start, end + 1)); } catch (e) { return null; }
      if (!obj || typeof obj !== 'object' || VERBS.indexOf(obj.verb) < 0) return null;
      return {
        verb: obj.verb,
        threadTitle: isNonEmptyString(obj.threadTitle) ? obj.threadTitle : undefined,
        text: isNonEmptyString(obj.text) ? obj.text : undefined,
      };
    }
