    // --- reply-to-speech (conversation mode) ---
    // Every voice-sent message arms a reply watch on the target session. The
    // watch only starts accumulating once the EXACT message we sent is claimed
    // into a turn ('agent/inbox/claimed' with message.id match): without that
    // gate, a question spoken while the agent is already mid-turn would pull
    // the current turn's text as its "answer". After claim, assistant/message
    // texts accumulate; when the agent goes idle the last non-empty text is
    // spoken at priority 0 (user reply), preempting acks. route_current
    // targets speak bare; other threads get an "On ..." prefix. A hard
    // lifetime caps stale watches (masked by ctx.timeout).
    ThreadManager.prototype.armReply = function (id, msgId) {
      var st = this.state;
      var w = st.replyWatch.get(id);
      if (!w) {
        w = { texts: [], armedAt: Date.now(), msgId: msgId, claimed: false };
        st.replyWatch.set(id, w);
      } else {
        w.texts = [];
        w.armedAt = Date.now();
        w.claimed = false;
      }
      if (isNonEmptyString(msgId)) w.msgId = msgId;
      var armed = w.armedAt;
      ctx.timeout(REPLY_WATCH_MAX_MS).then(function () {
        var cur = st.replyWatch.get(id);
        if (cur && cur.armedAt === armed) st.replyWatch.delete(id);
      }, function () { /* never rejects */ });
      return w;
    };
