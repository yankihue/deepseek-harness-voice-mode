    ThreadManager.prototype.message = function (id, text) {
      var st = this.state;
      if (!isNonEmptyString(text)) return Promise.resolve({ ok: false, code: 'bad_args', message: 'text expected' });
      var agent = liveAgent(st.svc, id);
      if (!agent) return Promise.resolve({ ok: false, code: 'no_such_thread', message: 'no live thread ' + id });
      try {
        var wake = this.makeUserMessage(text);
        agent.send(wake, 'next-step', true);
        this.touch(id, { watching: true });
        this.armReply(id, wake.id);
        st.queue.push('Got it.', 1);
        return Promise.resolve({ ok: true, id: id });
      } catch (err) {
        return Promise.resolve({ ok: false, code: 'delivery_failed', message: String(err && err.message || err) });
      }
    };
