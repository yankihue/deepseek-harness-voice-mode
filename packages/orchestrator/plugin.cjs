    // Collect the watch's last non-empty assistant text and speak it back.
    // Returns true when an utterance was actually queued.
    ThreadManager.prototype.speakReply = function (id) {
      var st = this.state;
      var w = st.replyWatch.get(id);
      if (!w) return false;
      if (!w.claimed) return false; // message not consumed yet: keep the watch for the next idle
      st.replyWatch.delete(id);
      var text = null;
      for (var i = w.texts.length - 1; i >= 0; i--) {
        var t = sanitizeSpeech(w.texts[i]);
        if (t) { text = t; break; }
      }
      if (!text) return false;
      // stale low-priority acks pushed since the watch armed would play AFTER
      // the answer (priority insert order) — drop them ("Got it." is moot once
      // the real reply speaks, and it preempts any active ack anyway)
      var pending = st.queue.pending;
      for (var j = pending.length - 1; j >= 0; j--) {
        if (pending[j].priority >= 1 && pending[j].ts >= w.armedAt) pending.splice(j, 1);
      }
      var spoken = (st.conversationId === id) ? text : 'On "' + threadName(st, id) + '": ' + text;
      var queued = st.queue.push(spoken, 0);
      if (queued) {
        // suppress the immediately-following "Thread ... is idle" announce
        this.lastSpoke.set(id, { status: Date.now(), end: Date.now(), error: Date.now(), goal: Date.now() });
      }
      return queued;
    };
